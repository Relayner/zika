  function srcKey() {
    const H = window.HSK || {}, P = window.PHON || {};
    const tag = v => (v && v.length ? v.length + '·' + (v[0] && v[0][0]) + (v[v.length - 1] && v[v.length - 1][0]) : '0');
    return [tag(H[1]), tag(H[2]), tag(H[3]), tag(window.FREQ), tag(P.CONFUSE), tag(P.NG_PAIRS)].join('|');
  }
  let memoCache = null;
  function memo() {
    const key = srcKey();
    if (!memoCache || memoCache.key !== key) memoCache = { key, bank: null, built: null, ptr: null };
    return memoCache;
  }

