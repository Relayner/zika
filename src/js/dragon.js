/* Наставник Лун 龙教头: напоминания с полудня, настроение зависит от времени и недобранных очков. */
window.Dragon = (() => {
  const MOODS = [
    { img: 'dragon-1', title: 'Наставник Лун ждёт с добром' },
    { img: 'dragon-2', title: 'Наставник Лун волнуется' },
    { img: 'dragon-3', title: 'Наставник Лун сердится' },
    { img: 'dragon-4', title: 'Наставник Лун теряет терпение' },
  ];
  const PHRASES = [
    ['Полдень миновал. {n} очков до перехода — начнём, пока солнце высоко?',
     'Лун потягивается на черепице: «Небольшая тренировка — и день зачтён».',
     'Свиток дня ещё пуст. {n} очков — это минут двадцать, не больше.',
     'Лун машет хвостом: «Чай выпит? Тогда {n} очков — и гуляй».',
     'Хороший воин тренируется до заката. Осталось {n}.',
     'Лун подмигивает: «Сундук сам себя не заработает».'],
    ['Лун поглядывает на солнце: до перехода ещё {n}. День короче, чем кажется.',
     'Лун грызёт кончик кисти: «{n} очков… успеем?»',
     'Полдня прошло, а свиток дня почти пуст: {n} до перехода.',
     'Лун ходит кругами по крыше: «Не откладывай на вечер двадцать минут дела».',
     'Ещё {n} очков — иначе вечером будет неловко. Мне. За тебя.',
     'Лун вздыхает: «Карточки скучают. И я скучаю».'],
    ['Лун постукивает когтем по черепице: {n} очков. Я жду.',
     'Дым из ноздрей: «Солнце садится, а перехода нет. {n}!»',
     'Лун свернулся у двери и не уйдёт, пока не увидит {n} очков.',
     '«Поход не прощает пустых дней», — Лун смотрит не мигая. {n} до перехода.',
     'Лун точит когти: «Двадцать минут. Всего двадцать минут. {n} очков».',
     'Хвост Луна хлещет по черепице: до перехода {n}.'],
    ['В темноте светятся глаза Луна: «{n} очков — или на рассвете поход откатится. Я приду посмотреть».',
     '«Дракон помнит все пропущенные дни», — шепчет Лун из тени. {n} до перехода.',
     'Гром над крышей. Это не гроза — это Лун. {n} очков до перехода.',
     'Лун уже не просит. Лун ждёт {n} очков. Молча. В темноте.',
     '«Завтра ранг может пасть. Решай сейчас». Чешуя Луна блестит в лунном свете. {n}!',
     'Последние часы дня. {n} очков между тобой и откатом. Лун наблюдает.'],
  ];
  /* 0..1 — насколько пора волноваться; -1 — дракон молчит (утро или день зачтён) */
  function urgency(t, now = new Date()) {
    if (!t || t.done) return -1;
    const h = now.getHours() + now.getMinutes() / 60;
    if (h < 12) return -1;
    const timeF = Math.min(1, (h - 12) / 10);
    const remF = Math.min(1, t.toCap / Campaign.CAP);
    return Math.min(1, timeF * 0.65 + remF * 0.35);
  }
  const moodIdx = u => (u < 0 ? -1 : u < 0.33 ? 0 : u < 0.52 ? 1 : u < 0.74 ? 2 : 3);
  function phrase(m, t, now = new Date()) {
    const list = PHRASES[Math.max(0, Math.min(3, m))];
    const seed = now.getDate() * 7 + now.getHours();
    return list[seed % list.length].replace('{n}', String(Math.round(t.toCap)));
  }
  /* null — молчит; иначе { mood, img, title, text, t } */
  function state(campaign, attempts, now = new Date()) {
    if (typeof window.__dragonForce === 'number') {
      const t = Campaign.todayState(campaign, attempts);
      const m = Math.max(0, Math.min(3, window.__dragonForce));
      return { mood: m, img: MOODS[m].img, title: MOODS[m].title, text: phrase(m, { toCap: t.toCap || 400 }, now), t };
    }
    const t = Campaign.todayState(campaign, attempts, now.getTime());
    const u = urgency(t, now);
    const m = moodIdx(u);
    return m < 0 ? null : { mood: m, img: MOODS[m].img, title: MOODS[m].title, text: phrase(m, t, now), t, u };
  }
  return { MOODS, PHRASES, urgency, moodIdx, phrase, state };
})();
