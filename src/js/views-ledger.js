/* Переключатель методики учёта в настройках и объяснение, что именно меняется. */
window.LedgerUI = (() => {
  const { state, actions, esc, fmt, toast, sheet, closeSheet, confirm, persist, render, nav } = App;

  /* Чем тестовая методика отличается от текущей — списком, без обещаний */
  const DIFFS = [
    ['Оценка уровня', 'Сейчас уровень — это «набралось 20 слов на уровень». В тестовой считается мастерство каждого слова по четырём полосам (чтение, слух, набор, от руки) с потолком по виду проверки: прочитал урок — не выше 0.30, узнал из вариантов — не выше 0.60, набрал сам — 0.80, сдал спринт — 0.90, экзамен — 1.00. Рядом с процентом всегда стоит «по проверкам».'],
    ['Ошибка называет привычку', 'Неверный вариант в тесте помечен ловушкой: тон-близнец, похожий знак, не то счётное слово, 不 вместо 没. Разбор показывает правило и чем это отличается от русского, а сама ловушка уходит в отдельные повторения.'],
    ['Что спрашивать дальше', 'Провалили слово на слух — оно вернётся раньше, но другим заданием, а не тем же самым. Прошли уверенно — отпускается.'],
    ['Грамматика проверяется', 'Правила блоков перестают быть текстом: по каждому есть задания — выбрать форму, найти ошибку, вписать частицу, собрать предложение.'],
    ['Где тонко', 'На главной — одна зона, которая сейчас слабее всего, и до трёх шагов с причиной одной фразой, а не «слабое место дня» без объяснения.'],
    ['Очки', 'Верный тычок быстрее 2,5 секунды не оплачивается, попытка, похожая на угадывание, стоит вдвое дешевле. Зато материал ниже вашего уровня больше не режется в пять раз — платит только новизна.'],
  ];

  function summaryRow(v, s, cur) {
    if (!s) return `<div class="lg-row"><b>${Ledger.VERS[v].zh} ${Ledger.VERS[v].ru}</b><span class="hint">книга ещё не заведена — появится при первом переключении</span></div>`;
    return `<div class="lg-row ${cur ? 'on' : ''}"><b>${Ledger.VERS[v].zh} ${Ledger.VERS[v].ru}${cur ? ' · открыта' : ''}</b>
      <span class="hint">день похода ${s.days} · сегодня ${s.today} из ${s.cap} очк.${s.done ? ' ✓' : ''} · к повторению ${s.due} · блоков пройдено ${s.blocks}</span></div>`;
  }

  function panel() {
    if (!window.Ledger) return '';
    const cur = Ledger.active(state);
    const s = Ledger.summary(state);
    const ch = window.CHANNEL || {};
    return `<div class="panel">
      <div class="flabel">Методика учёта</div>
      <div class="seg">${['v1', 'v2'].map(v => `<button class="${cur === v ? 'on' : ''}" data-action="ver-set" data-v="${v}"><span class="zh">${Ledger.VERS[v].zh}</span> ${Ledger.VERS[v].ru}</button>`).join('')}</div>
      <div class="hint" style="margin-top:8px">${cur === 'v2'
        ? 'Открыта тестовая методика. Обе книги ведутся параллельно: вернётесь к текущей — там будет учтено всё, что вы сделали, но по её правилам.'
        : 'Открыта текущая методика — та же, что у всех. Тестовую можно включить и выключить в любой момент, прогресс не теряется.'}</div>
      <div class="lg-books">${summaryRow('v1', s.v1, cur === 'v1')}${summaryRow('v2', s.v2, cur === 'v2')}</div>
      <div class="btns mt0"><button class="btn btn-secondary btn-sm btn-block" data-action="ver-info">Что меняется в тестовой методике</button></div>
      ${ch.id === 'beta' ? '<div class="hint">Это тестовое приложение 字卡 β. У него отдельное хранилище: статистика не смешивается с основным приложением и ни на кого не влияет.</div>' : '<div class="hint">Основное приложение. Тестовая методика включается только вручную и только у вас.</div>'}
    </div>`;
  }

  actions['ver-info'] = () => sheet(`<h3 class="sh-t">Тестовая методика</h3>
    <div class="install-note"><p>Две книги учёта ведутся <b>одновременно</b>. Журнал занятий один, а выводы из него делаются по-разному: очки дня, повторения и оценка уровня считаются отдельно для каждой методики.</p>
    <p>Поэтому переключение ничего не ломает: поработали в тестовой, вернулись в текущую — там учтено всё, что произошло, но по её правилам. И наоборот.</p></div>
    <div class="wn">${DIFFS.map(([t, d]) => `<div class="wn-it"><b>${esc(t)}</b><div class="hint" style="margin:2px 0 0">${esc(d)}</div></div>`).join('')}</div>
    <button class="btn btn-primary btn-block mt" data-close>Понятно</button>`);

  actions['ver-set'] = async el => {
    const v = el.dataset.v;
    if (!Ledger.VERS[v] || Ledger.active(state) === v) return;
    const to = Ledger.VERS[v];
    const ok = await confirm(
      v === 'v2'
        ? 'Включить тестовую методику? Прогресс не теряется: текущая книга останется как есть и продолжит пополняться. Вернуться можно в любой момент.'
        : 'Вернуться к текущей методике? Тестовая книга сохранится и продолжит пополняться — можно будет переключиться обратно.',
      { ok: 'Переключить', title: to.zh + ' ' + to.ru });
    if (!ok) return;
    const changed = Ledger.switchTo(state, v) || [];
    if (changed.length) { try { await Store.putAttempts(changed); } catch (e) { /* пересчитается при следующем запуске */ } }
    state.cardStats = Stats.cardStats(state.attempts);
    await App.persistNow();
    App.updateBadge();
    toast(v === 'v2' ? 'Тестовая методика включена — всё пересчитано по её правилам' : 'Вернулись к текущей методике', 3200);
    render();
  };

  return { panel, DIFFS };
})();
